# Ввод длин рёбер
a = float(input("Введите длину a: "))
b = float(input("Введите ширину b: "))
c = float(input("Введите высоту c: "))

# Расчёт объёма и площади поверхности
V = a * b * c
S = 2 * (a * b + b * c + a * c)

# Вывод результатов
print(f"Объём V = {V}")
print(f"Площадь поверхности S = {S}")
