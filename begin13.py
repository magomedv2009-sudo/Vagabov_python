PI = 3.14
R1 = float(input("Введите внешний радиус R1 (R1 > R2): "))
R2 = float(input("Введите внутренний радиус R2: "))

S1 = PI * R1 ** 2
S2 = PI * R2 ** 2
S3 = S1 - S2

print(f"Площадь большего круга S1 = {S1}")
print(f"Площадь меньшего круга S2 = {S2}")
print(f"Площадь кольца S3 = {S3}")
